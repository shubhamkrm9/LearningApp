/**
 * The Security State Machine represents the app's trust lifecycle.
 */
export enum SecurityState {
  INITIALIZING = 'INITIALIZING',
  DEVICE_VERIFIED = 'DEVICE_VERIFIED',
  AUTHENTICATED = 'AUTHENTICATED',
  RUNTIME_MONITORING = 'RUNTIME_MONITORING',
  RISK_INCREASED = 'RISK_INCREASED',
  SESSION_REVOKED = 'SESSION_REVOKED',
  LOCKDOWN = 'LOCKDOWN',
  LOGOUT = 'LOGOUT'
}

/**
 * Types of Security Threats our modules can detect.
 */
export enum ThreatType {
  // Module 1: Reverse Engineering
  ROOT_DETECTED = 'ROOT_DETECTED',
  HOOKING_DETECTED = 'HOOKING_DETECTED',
  DEBUGGER_ATTACHED = 'DEBUGGER_ATTACHED',
  EMULATOR_DETECTED = 'EMULATOR_DETECTED',
  JNI_MODIFIED = 'JNI_MODIFIED',

  // Module 2: APK Repackaging
  SIGNATURE_MISMATCH = 'SIGNATURE_MISMATCH',
  DEX_TAMPERED = 'DEX_TAMPERED',
  MANIFEST_TAMPERED = 'MANIFEST_TAMPERED',

  // Module 3: Memory Protection
  MEMORY_DUMP_ATTEMPT = 'MEMORY_DUMP_ATTEMPT',
  PTRACE_DETECTED = 'PTRACE_DETECTED',

  // Module 4: Overlay Protection
  OVERLAY_ACTIVE = 'OVERLAY_ACTIVE',
  OBSCURED_TOUCH = 'OBSCURED_TOUCH',

  // Module 5: Accessibility
  UNKNOWN_ACCESSIBILITY_SERVICE = 'UNKNOWN_ACCESSIBILITY_SERVICE',
  AUTOMATION_SERVICE = 'AUTOMATION_SERVICE',

  // Other
  DEVICE_MISMATCH = 'DEVICE_MISMATCH',
  REPLAY_ATTACK = 'REPLAY_ATTACK'
}

/**
 * Severity levels for Risk Scoring
 */
export enum RiskSeverity {
  LOW = 'LOW',
  MEDIUM = 'MEDIUM',
  HIGH = 'HIGH',
  CRITICAL = 'CRITICAL'
}

/**
 * Context represents the current screen or user action, 
 * which dictates how severe a threat is.
 */
export enum AppContext {
  BACKGROUND = 'BACKGROUND',
  HOME_SCREEN = 'HOME_SCREEN',
  LEARNING_MODULE = 'LEARNING_MODULE',
  LOGIN_SCREEN = 'LOGIN_SCREEN',
  PAYMENT_SCREEN = 'PAYMENT_SCREEN',
  ASSESSMENT_SCREEN = 'ASSESSMENT_SCREEN'
}

/**
 * An event generated by one of the 5 Security Modules.
 */
export interface SecurityEvent {
  threatType: ThreatType;
  severity: RiskSeverity;
  timestamp: number;
  details?: string;
}
